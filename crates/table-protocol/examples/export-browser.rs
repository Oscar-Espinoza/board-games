//! Emit the module consumed by every game release and transport tests.
use table_protocol::*;
fn main() {
    println!("// Generated by table-protocol; do not edit.");
    for (key, value) in [
        ("PROTOCOL_VERSION", u64::from(PROTOCOL_VERSION)),
        ("MAX_MESSAGE", MAX_MESSAGE as u64),
        ("GUEST_WAIT_MS", GUEST_WAIT_MS),
        ("HOST_WAIT_MS", HOST_WAIT_MS),
    ] {
        println!("export const {key} = {value};");
    }
    for (key, value) in [
        ("CHANNEL_NAME", channel_name()),
        ("SEAT_NAMESPACE", seat_namespace()),
        ("ACTION_NAMESPACE", action_namespace()),
    ] {
        println!("export const {key} = '{}';", value);
    }
}
